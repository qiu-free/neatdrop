it('opens a help topic addressed by an existing deep link', () => {
  window.history.replaceState(null, '', '#help-topic-supported-files')
  render(<HelpPage />)
  const topic = document.getElementById('help-topic-supported-files')!
  expect(topic).toHaveAttribute('open')
  expect(topic).toHaveTextContent('不递归进入子目录')
  window.history.replaceState(null, '', '/')
})

it('shows help details below the selected topic and keeps only one topic expanded', () => {
  render(<HelpPage />)
  const first = screen.getByText('支持的文件和目录', { selector: 'summary' })
  const next = screen.getByText('Office 与表格的读取范围', { selector: 'summary' })
  const topics = screen.getByRole('region', { name: '帮助主题' })
  expect(topics.querySelectorAll('details[open]')).toHaveLength(0)
  expect(first.closest('details')).not.toHaveAttribute('open')
  expect(screen.queryByText(/DOCX 段落与表格/)).not.toBeInTheDocument()
  fireEvent.click(first)
  expect(first.closest('details')).toHaveAttribute('open')
  expect(screen.getByText(/只读取所选目录的直接子文件/)).toBeInTheDocument()
  fireEvent.click(next)
  expect(first.closest('details')).not.toHaveAttribute('open')
  expect(next.closest('details')).toHaveAttribute('open')
  expect(topics.querySelectorAll('details[open]')).toHaveLength(1)
  expect(screen.getByText(/DOCX 段落与表格/)).toBeInTheDocument()
  fireEvent.click(next)
  expect(topics.querySelectorAll('details[open]')).toHaveLength(0)
})

it('describes supported Office content without promising formulas, old Office or scanned PDF support', () => {
  render(<HelpPage supportedExtensions={['.pdf', '.txt', '.docx', '.pptx', '.xlsx', '.csv']} />)
  fireEvent.change(screen.getByRole('searchbox', { name: '搜索使用说明' }), { target: { value: 'XLSX' } })
  const supportedSummary = screen.getByText('支持的文件和目录', { selector: 'summary' })
  fireEvent.click(supportedSummary)
  expect(supportedSummary.closest('details')).toHaveTextContent('DOCX')
  const officeSummary = screen.getByText('Office 与表格的读取范围', { selector: 'summary' })
  fireEvent.click(officeSummary)
  expect(officeSummary.closest('details')).toHaveTextContent('不会计算公式')
  fireEvent.change(screen.getByRole('searchbox', { name: '搜索使用说明' }), { target: { value: '暂不支持' } })
  const unsupportedSummary = screen.getByText('暂不支持的能力', { selector: 'summary' })
  fireEvent.click(unsupportedSummary)
  expect(unsupportedSummary.closest('details')).toHaveTextContent('旧 DOC / XLS / PPT')
  expect(unsupportedSummary.closest('details')).not.toHaveTextContent('DOCX / PPTX')
})
