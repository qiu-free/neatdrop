import { fireEvent, render, screen } from '@testing-library/react'
import { TutorialExercise } from './TutorialExercise'

function reachReview() {
  fireEvent.click(screen.getByRole('button', { name: '载入内置样例' }))
  fireEvent.click(screen.getByRole('button', { name: '查看 演示收据.png' }))
  expect(screen.getByRole('checkbox', { name: '选择 演示收据.png' })).not.toBeChecked()
  expect(screen.getByRole('complementary', { name: '练习文件详情' })).toHaveTextContent('合计：28.00 元')
  fireEvent.click(screen.getByRole('checkbox', { name: '选择 演示收据.png' }))
  fireEvent.click(screen.getByRole('button', { name: '继续：做一次本地分析' }))
  fireEvent.click(screen.getByRole('button', { name: '模拟本地分析' }))
}

it('reviews candidates explicitly, confirms the plan separately and visits library before undo without network', () => {
  const onComplete = vi.fn()
  const fetchSpy = vi.spyOn(globalThis, 'fetch')
  render(<TutorialExercise completed={false} onComplete={onComplete} />)
  expect(screen.getByText(/不会读取本机文件，也不会访问 API/)).toBeInTheDocument()
  reachReview()
  expect(screen.getByRole('navigation', { name: '练习工作流' })).toHaveTextContent('资料库')
  expect(screen.getByText('待复核候选：票据凭证 · 消费小票')).toBeInTheDocument()
  expect(screen.getByRole('button', { name: '生成整理计划' })).toBeDisabled()
  fireEvent.click(screen.getByRole('button', { name: '一键审核已选项（1）' }))
  expect(screen.getByRole('button', { name: '生成整理计划' })).toBeEnabled()
  fireEvent.change(screen.getByLabelText('演示收据.png 的练习分类'), { target: { value: 'life' } })
  expect(screen.getByRole('button', { name: '生成整理计划' })).toBeDisabled()
  expect(screen.getByRole('button', { name: '一键审核已选项（1）' })).toBeEnabled()
  fireEvent.click(screen.getByRole('button', { name: '一键审核已选项（1）' }))
  fireEvent.click(screen.getByRole('button', { name: '生成整理计划' }))
  expect(screen.getByLabelText('练习原件位置')).toHaveTextContent('C:/安全练习/演示收据.png')
  expect(screen.getByLabelText('练习副本位置')).toHaveTextContent('C:/安全练习/08_生活服务/演示收据.png')
  expect(screen.getByRole('button', { name: '模拟确认并生成副本' })).toBeDisabled()
  expect(onComplete).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('checkbox', { name: '我已核对计划，确认生成模拟副本并保留原件' }))
  fireEvent.click(screen.getByRole('button', { name: '模拟确认并生成副本' }))
  expect(screen.getByRole('heading', { name: '资料库查看副本' })).toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: '查看归档副本' }))
  expect(screen.getByRole('complementary', { name: '练习副本详情' })).toHaveTextContent('合计：28.00 元')
  fireEvent.click(screen.getByRole('button', { name: '查看操作记录' }))
  fireEvent.click(screen.getByRole('button', { name: '模拟撤回副本' }))
  expect(screen.getByRole('status')).toHaveTextContent('模拟已撤回，原件仍保留')
  expect(onComplete).toHaveBeenCalledOnce()
  expect(fetchSpy).not.toHaveBeenCalled()
  fetchSpy.mockRestore()
})

