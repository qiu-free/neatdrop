import { fireEvent, render, screen } from '@testing-library/react'
import { ProductPage } from '../components/ProductPage'
vi.mock('../runtimeCapabilities', async () => import('./capabilities'))

it('explains browser memory boundaries and offers working onboarding actions without service requests', () => {
  const onPractice = vi.fn(), onWorkbench = vi.fn(), onHelp = vi.fn()
  const requests = vi.spyOn(globalThis, 'fetch')
  render(<ProductPage onPractice={onPractice} onWorkbench={onWorkbench} onHelp={onHelp} />)
  expect(screen.getByText(/当前为网页体验/)).toBeInTheDocument()
  expect(screen.getByText(/没有复制你的磁盘文件/)).toBeInTheDocument()
  expect(screen.getByText(/网页不运行实时 OCR/)).toBeInTheDocument()
  expect(screen.queryByText(/副本创建在同一文件夹/)).not.toBeInTheDocument()
  const flow = screen.getByRole('region', { name: '一次整理，按顺序完成' })
  expect(flow).not.toHaveTextContent('选择一个本机目录')
  expect(flow).not.toHaveTextContent('云端分析需另行授权')
  expect(flow).not.toHaveTextContent('复制成功后')
  fireEvent.click(screen.getByRole('button', { name: '开始安全练习' }))
  fireEvent.click(screen.getByRole('button', { name: '进入整理工作台' }))
  fireEvent.click(screen.getByRole('button', { name: '查看详细使用说明' }))
  expect(onPractice).toHaveBeenCalledOnce()
  expect(onWorkbench).toHaveBeenCalledOnce()
  expect(onHelp).toHaveBeenCalledOnce()
  expect(requests).not.toHaveBeenCalled()
  requests.mockRestore()
})
